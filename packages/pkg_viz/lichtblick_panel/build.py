"""Bundle the panel into dist/extension.js and pack georg-task-manager-panel-<version>.foxe.

No npm, no bundler: model.js is wrapped as an inner module, extension.js uses it as `model`.
A .foxe file is a zip with package.json and dist/extension.js.

    python3 build.py            # -> dist/extension.js, georg-task-manager-panel-0.1.0.foxe
    python3 build.py --install  # also unpack into ~/.lichtblick-suite/extensions (desktop app)
Install in Lichtblick: Extensions -> install from file, or copy the unpacked folder to
~/.lichtblick-suite/extensions/autonohm.georg-task-manager-panel-0.1.0/
"""

import json
import os
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))


def bundle() -> str:
    with open(os.path.join(HERE, 'src', 'model.js'), encoding='utf-8') as f:
        model = f.read()
    with open(os.path.join(HERE, 'src', 'extension.js'), encoding='utf-8') as f:
        extension = f.read()
    return (
        '"use strict";\n'
        '// generated by build.py from src/model.js and src/extension.js - do not edit\n'
        'const model = (function () {\n'
        '  const module = { exports: {} };\n'
        f'{model}\n'
        '  return module.exports;\n'
        '})();\n'
        f'{extension}\n'
    )


def main():
    with open(os.path.join(HERE, 'package.json'), encoding='utf-8') as f:
        pkg = json.load(f)
    os.makedirs(os.path.join(HERE, 'dist'), exist_ok=True)
    out_js = os.path.join(HERE, 'dist', 'extension.js')
    with open(out_js, 'w', encoding='utf-8') as f:
        f.write(bundle())
    foxe = os.path.join(HERE, f"{pkg['name']}-{pkg['version']}.foxe")
    with zipfile.ZipFile(foxe, 'w', zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(HERE, 'package.json'), 'package.json')
        z.write(out_js, 'dist/extension.js')
        readme = os.path.join(HERE, 'README.md')
        if os.path.exists(readme):
            z.write(readme, 'README.md')
    print(foxe)
    if '--install' in sys.argv:
        # same folder name the desktop app uses: <publisher>.<name>-<version>
        target = os.path.join(os.path.expanduser('~'), '.lichtblick-suite', 'extensions',
                              f"{pkg['publisher']}.{pkg['name']}-{pkg['version']}")
        os.makedirs(os.path.join(target, 'dist'), exist_ok=True)
        shutil.copy(os.path.join(HERE, 'package.json'), target)
        shutil.copy(out_js, os.path.join(target, 'dist', 'extension.js'))
        shutil.copy(os.path.join(HERE, 'README.md'), target)
        print(f'installed to {target} (restart Lichtblick)')


if __name__ == '__main__':
    main()
